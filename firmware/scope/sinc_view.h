//----------------------------------------------------------------------------------------------------------------------------------
// sinc_view.h - sin(x)/x interpolation for the trace between samples (GitHub issue #2 follow-up, option C of
// docs/mockups/acq-fast-timediv.html).
//
// At 200 MSa/s the fastest time bases hold fewer than ten samples a division (20 ns/div four, 10 ns/div two). The
// front end's bandwidth (about 30 MHz) is far below half the sample rate (100 MHz), so the samples describe the signal
// completely and the curve between them can be computed: a windowed sinc, as bench scopes draw it. Straight lines
// between samples 12 or 25 px apart show a polygon instead.
//
// The taps are a Kaiser-windowed sinc in Q12 (sinc_view_lut.c, generated by firmware/tools/gen_sinc_table.py):
// SINCV_TAPS samples around the position, SINCV_PHASES positions between two samples. Row 0 is the identity: the curve
// passes through every sample. Integer only, no globals. Host-tested: host_tests/test_sinc_view.c.
//----------------------------------------------------------------------------------------------------------------------------------

#ifndef SINC_VIEW_H
#define SINC_VIEW_H

#include "types.h"

#define SINCV_TAPS     8
#define SINCV_PHASES   32
#define SINCV_Q        12

extern const int16 sincv_lut[SINCV_PHASES][SINCV_TAPS];

//The interpolated value of v[0..n-1] at position `pos` in samples, Q16 (0 = v[0], 65536 = v[1]); positions past the
//last sample give the last sample. Samples before v[0] and after v[n-1] read as the edge sample. n >= 1.
int32 sincv_at(const int16 *v, int32 n, uint32 pos);

#endif // SINC_VIEW_H
