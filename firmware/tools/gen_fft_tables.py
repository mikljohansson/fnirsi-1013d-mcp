#!/usr/bin/env python3
"""Generate firmware/scope/fx_fft_tables.c: the build-time tables of the fixed-point FFT (fx_fft.c).

The target has no libm and no FPU, so every transcendental value the FFT needs comes from here:
  fx_cos_tab   cos(2 pi k / 16384) in Q30 for k = 0..4096 (quarter wave; sin and the other quadrants by symmetry)
  fx_log2_tab  log2(1 + i / 256) in Q16 for i = 0..256 (dB conversion, linear interpolation between entries)
  fx_flattop   the five flat-top window coefficients in Q30 (Matlab flattopwin)

The output is committed; host_tests/test_fft.py regenerates it and fails if the committed file differs.
Usage: gen_fft_tables.py [-o path]   (default: stdout)
"""
import argparse
import math
import sys

LOG2_MAX = 14
N_MAX = 1 << LOG2_MAX
Q30 = 1 << 30
FLATTOP = (0.21557895, 0.41663158, 0.277263158, 0.083578947, 0.006947368)


def generate():
    cos_tab = [int(round(math.cos(2 * math.pi * k / N_MAX) * Q30)) for k in range(N_MAX // 4 + 1)]
    log2_tab = [int(round(math.log2(1 + i / 256) * 65536)) for i in range(257)]
    flat = [int(round(a * Q30)) for a in FLATTOP]
    out = []
    out.append("// fx_fft_tables.c - generated by firmware/tools/gen_fft_tables.py, do not edit.")
    out.append("// Build-time tables for fx_fft.c (no libm on the target).")
    out.append("")
    out.append('#include "fx_fft.h"')
    out.append("")
    out.append("//cos(2 pi k / %d) in Q30, k = 0..%d" % (N_MAX, N_MAX // 4))
    out.append("const int32 fx_cos_tab[%d] =\n{" % len(cos_tab))
    for i in range(0, len(cos_tab), 8):
        out.append("  " + ", ".join("%d" % v for v in cos_tab[i:i + 8]) + ",")
    out.append("};")
    out.append("")
    out.append("//log2(1 + i / 256) in Q16, i = 0..256")
    out.append("const uint32 fx_log2_tab[257] =\n{")
    for i in range(0, 257, 12):
        out.append("  " + ", ".join("%d" % v for v in log2_tab[i:i + 12]) + ",")
    out.append("};")
    out.append("")
    out.append("//Flat-top window a0..a4 in Q30 (Matlab flattopwin: %s)" % ", ".join(repr(a) for a in FLATTOP))
    out.append("const int32 fx_flattop[5] = { %s };" % ", ".join("%d" % v for v in flat))
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-o", "--output")
    args = ap.parse_args()
    text = generate()
    if args.output:
        with open(args.output, "w", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
