#!/usr/bin/env python3
"""Generate firmware/scope/sinc_view_lut.c: the sin(x)/x interpolation taps of sinc_view.c.

    python3 -I firmware/tools/gen_sinc_table.py -o firmware/scope/sinc_view_lut.c
    python3 -I firmware/tools/gen_sinc_table.py --check firmware/scope/sinc_view_lut.c

A Kaiser-windowed sinc, TAPS taps for each of PHASES positions between two samples, as Q12 integers. Row p gives the
value at sample 3 + p / PHASES of the eight samples 0..7. Every row sums to exactly 4096 (a constant input stays that
constant) and row 0 is the identity (the trace passes through every sample). host_tests/test_sinc_view.c checks both
and the reconstruction error.
"""
import argparse
import math
import sys

TAPS = 8
PHASES = 32
Q = 12
BETA = 5.0


def i0(x: float) -> float:
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


def row(phase: int) -> list[int]:
    f = phase / PHASES
    half = TAPS // 2
    h = []
    for k in range(TAPS):
        d = (k - (half - 1)) - f
        s = 1.0 if d == 0 else math.sin(math.pi * d) / (math.pi * d)
        w = i0(BETA * math.sqrt(max(0.0, 1 - (d / half) ** 2))) / i0(BETA)
        h.append(s * w)
    scale = (1 << Q) / sum(h)
    q = [round(v * scale) for v in h]
    q[max(range(TAPS), key=lambda k: abs(q[k]))] += (1 << Q) - sum(q)
    return q


def text() -> str:
    out = ["//Generated by firmware/tools/gen_sinc_table.py (Kaiser beta %.1f): do not edit. See sinc_view.h." % BETA, "",
           '#include "sinc_view.h"', "",
           "const int16 sincv_lut[SINCV_PHASES][SINCV_TAPS] =", "{"]
    for p in range(PHASES):
        out.append("  { " + ", ".join("%5d" % v for v in row(p)) + " },")
    out += ["};", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--output")
    ap.add_argument("--check", help="compare with an existing file")
    a = ap.parse_args()
    t = text()
    if a.check:
        with open(a.check, encoding="utf-8", newline="") as fh:
            same = fh.read() == t
        print("sinc table: %s" % ("identical to the generator" if same else "DIFFERS from the generator"))
        return 0 if same else 1
    if a.output:
        with open(a.output, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(t)
    else:
        sys.stdout.write(t)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
